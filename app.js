function getTracks(){ try{ return JSON.parse(localStorage.getItem('anonima_tracks')||'[]'); }catch(e){ return []; } }
function saveTracks(t){ localStorage.setItem('anonima_tracks', JSON.stringify(t)); }
const audioURLs = {};

function upload(){
  const titleEl = document.getElementById('title');
  const licenseEl = document.getElementById('license');
  const fileInput = document.getElementById('file');

  const title = titleEl.value.trim();
  const license = licenseEl.value;
  const file = fileInput.files && fileInput.files[0];

  if(!title){ alert('Enter a title'); titleEl.focus(); return; }
  if(!file){ alert('Select an mp3 file'); return; }

  const id = Date.now().toString();
  try {
    const url = URL.createObjectURL(file);
    audioURLs[id] = url;
  } catch(e){
    alert('Browser audio error: ' + e.message);
    return;
  }

  const tracks = getTracks();
  tracks.unshift({ id, title, license, keep:0, skip:0, status:'pending', hasAudio:true, name: file.name });
  saveTracks(tracks);

  titleEl.value='';
  fileInput.value='';
  render();
  alert('Uploaded to The Vault!');
}

function vote(id, type){
  const tracks=getTracks();
  const t=tracks.find(x=>x.id===id);
  if(!t) return;
  t[type]++;
  if(t.keep >= 2 && t.status === 'pending'){
    t.status = 'live';
  }
  saveTracks(tracks); render();
}

function render(){
  const tracks=getTracks();
  const vault = tracks.filter(t=>t.status==='pending');
  const live = tracks.filter(t=>t.status==='live');

  document.getElementById('vault').innerHTML = vault.map(t=>`
    <div class="track">
      <b>${t.title}</b> <span style="color:#888;font-size:12px">${t.license}</span><br>
      ${audioURLs[t.id]? `<audio controls src="${audioURLs[t.id]}" style="width:100%;margin:10px 0"></audio><br>` : `<p style="color:#666;font-size:12px">[re-upload the file to listen in this session]</p>`}
      <button onclick="vote('${t.id}','keep')">KEEP (${t.keep})</button>
      <button onclick="vote('${t.id}','skip')">SKIP (${t.skip})</button>
    </div>`).join('') || '<p style="color:#555">Empty</p>';

  document.getElementById('live').innerHTML = live.map(t=>`
    <div class="track"><b>${t.title}</b> <span style="color:#888;font-size:12px">${t.license}</span>
    ${audioURLs[t.id]? `<br><audio controls src="${audioURLs[t.id]}" style="width:100%;margin:10px 0"></audio>` : ``}
    </div>
  `).join('') || '<p style="color:#555">Empty</p>';
}
render();

